// node homepage/build.mjs          writes the cards for the pages with show: true into ../index.html
// node homepage/build.mjs --check  fails if index.html does not match pages.json (used in CI)
// Hidden pages are left out entirely, so the published site never names them.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const { pages } = JSON.parse(readFileSync(new URL('homepage/pages.json', root), 'utf8'));
const indexUrl = new URL('index.html', root);
const html = readFileSync(indexUrl, 'utf8');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const shown = pages.filter((p) => p.show);

// Icons share one hand: 64x64, round 3px lines in the tile's ink, one filled highlight in the tile's light tone.
const ICONS = {
  binder: `<rect x="10" y="8" width="44" height="50" rx="5"/><path d="M18 8v50"/><circle cx="14" cy="18" r="1.6" class="dot"/><circle cx="14" cy="33" r="1.6" class="dot"/><circle cx="14" cy="48" r="1.6" class="dot"/><rect x="24" y="15" width="11" height="15" rx="2"/><rect x="39" y="15" width="11" height="15" rx="2" class="hi"/><rect x="24" y="35" width="11" height="15" rx="2"/><rect x="39" y="35" width="11" height="15" rx="2"/><path d="M44.5 19.5l1.3 2.7 3 .4-2.2 2 .5 2.9-2.6-1.4-2.6 1.4.5-2.9-2.2-2 3-.4z" class="spark"/>`,
  route: `<path d="M8 50c8 0 10-12 18-12s9 10 17 10 8-22 13-30" class="dash"/><circle cx="8" cy="50" r="4"/><circle cx="26" cy="38" r="4"/><circle cx="43" cy="48" r="4"/><path d="M38 15c3-5 8-7 12-7s9 2 12 7c-3 5-8 7-12 7s-9-2-12-7z" class="hi"/><circle cx="50" cy="15" r="3" class="dot"/>`,
  bell: `<path d="M32 8v5"/><path d="M20 40V28a12 12 0 0124 0v12l5 7H15z" class="hi"/><path d="M27 52a5 5 0 0010 0"/><path d="M8 24c-2 5-2 11 0 16M56 24c2 5 2 11 0 16M3 20c-4 8-4 16 0 24M61 20c4 8 4 16 0 24"/>`,
  hat: `<path d="M14 36c5-1 9-12 13-20s9-10 12-9c-2 4-1 9 1 14s5 11 10 15z" class="hi"/><path d="M8 38c8 3 40 3 48 0"/><rect x="25" y="44" width="14" height="14" rx="1"/><rect x="11" y="49" width="14" height="9" rx="1"/><rect x="39" y="52" width="14" height="6" rx="1"/><path d="M32 48v5"/>`,
  book: `<path d="M32 14c-6-4-14-5-22-4v40c8-1 16 0 22 4 6-4 14-5 22-4V10c-8-1-16 0-22 4z"/><path d="M32 14v40"/><circle cx="44" cy="30" r="7" class="hi"/><path d="M37 30h14"/><circle cx="44" cy="30" r="2" class="dot"/>`,
  train: `<rect x="14" y="8" width="36" height="40" rx="8" class="hi"/><rect x="19" y="14" width="26" height="12" rx="2"/><circle cx="23" cy="37" r="2.5" class="dot"/><circle cx="41" cy="37" r="2.5" class="dot"/><path d="M20 48l-6 10M44 48l6 10M17 54h30"/>`,
  coins: `<ellipse cx="24" cy="46" rx="14" ry="5"/><path d="M10 46v-8c0 3 6 5 14 5s14-2 14-5v8"/><ellipse cx="24" cy="38" rx="14" ry="5" class="hi"/><ellipse cx="42" cy="26" rx="13" ry="5"/><path d="M29 26v8M55 26v10c0 3-6 5-13 5"/><path d="M42 12v6M38 15h8" class="spark"/>`,
};
const icon = (name) => `<svg class="icon" viewBox="0 0 64 64" aria-hidden="true">${ICONS[name] ?? ICONS.book}</svg>`;

const cards = shown
  .map((p) =>
    [
      `\t\t\t<a class="tile" href="${esc(p.href)}" style="--tile:${p.color};--ink:${p.ink}">`,
      `\t\t\t\t${icon(p.icon)}`,
      `\t\t\t\t<span class="tile-title"${p.countdown ? ' id="countdownTitle"' : ''}>${esc(p.title)}</span>`,
      `\t\t\t\t<span class="tile-desc"${p.countdown ? ' id="countdownDesc"' : ''}>${esc(p.desc)}</span>`,
      `\t\t\t</a>`,
    ].join('\n'),
  )
  .join('\n\n');

// The countdown card fills in its title and date from countdown/config.json.
const countdownScript = shown.some((p) => p.countdown)
  ? `
\t\t<script>
\t\t\tfetch("countdown/config.json")
\t\t\t\t.then((res) => (res.ok ? res.json() : null))
\t\t\t\t.then((config) => {
\t\t\t\t\tif (!config) return;
\t\t\t\t\tdocument.getElementById("countdownTitle").textContent = config.headline.replace(/<[^>]+>/g, "");
\t\t\t\t\tconst target = new Date(config.target);
\t\t\t\t\tconst dateLabel = isNaN(target) ? config.footerLabel : target.toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" });
\t\t\t\t\tdocument.getElementById("countdownDesc").textContent = \`Counting down to \${dateLabel}.\`;
\t\t\t\t})
\t\t\t\t.catch(() => {});
\t\t</script>`
  : '';

const block = (name, body) => `<!-- ${name}:start (generated by homepage/build.mjs from homepage/pages.json) -->${body}<!-- ${name}:end -->`;
const replace = (text, name, body) => {
  const re = new RegExp(`<!-- ${name}:start[^]*?<!-- ${name}:end -->`);
  if (!re.test(text)) throw new Error(`index.html is missing the ${name} markers`);
  return text.replace(re, block(name, body));
};
let next = replace(html, 'pages', `\n${cards}\n\t\t\t`);
next = replace(next, 'scripts', `${countdownScript}\n\t\t`);

if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error('index.html does not match homepage/pages.json. Run: node homepage/build.mjs');
    process.exit(1);
  }
  console.log(`index.html matches: ${shown.length} shown, ${pages.length - shown.length} hidden`);
} else {
  writeFileSync(indexUrl, next);
  console.log(`index.html: ${shown.length} shown, ${pages.length - shown.length} hidden`);
}
