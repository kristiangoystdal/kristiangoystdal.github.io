import { launch, device, URL_BASE, TARGET } from './env.mjs'
let failed = 0
const check = (ok, name) => { console.log(`${ok ? 'OK  ' : 'FEIL'} ${name}`); if (!ok) failed++ }
const browser = await launch()
const ctx = await browser.newContext(device({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' }))
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('dialog', (d) => d.accept())
await page.addInitScript(() => localStorage.getItem('hideandseek.guide') || localStorage.setItem('hideandseek.guide', JSON.stringify({ state: { seen: true }, version: 0 })))
const settings = () => page.evaluate(() => JSON.parse(localStorage.getItem('hideandseek.v1')).state.settings)
await page.goto(URL_BASE)
await page.waitForFunction(() => JSON.parse(localStorage.getItem('hideandseek.v1') || '{}')?.state?.settings?.playArea?.length > 2, null, { timeout: 15000 })
let s = await settings()
check(s.playArea.length > 2 && s.areaAuto !== false, `ny bruker får automatisk spillområde i Oslo (${s.playArea.length} hjørner)`)
const rulesRow = page.getByRole('button', { name: /Spillstørrelse, linjer/ })
check(!(await rulesRow.textContent()).includes('hele nettet'), 'oppsettet sier ikke «hele nettet»')
await rulesRow.click()
const sheet = page.getByRole('dialog', { name: /Oppsett for/ })
check(await sheet.getByRole('radio', { name: 'Automatisk' }).getAttribute('aria-checked') === 'true', '«Automatisk» er valgt i oppsettet')
await sheet.getByRole('radio', { name: 'Hele nettet' }).click()
await page.waitForTimeout(400)
s = await settings()
check(s.playArea === null && s.areaAuto === false, '«Hele nettet» fjerner området')
await page.reload()
await page.waitForSelector('aside')
await page.waitForTimeout(2500)
s = await settings()
check(s.playArea === null, '«Hele nettet» blir værende etter omlasting (overskrives ikke av automatikken)')
await page.getByRole('button', { name: /Spillstørrelse, linjer/ }).click()
await page.getByRole('dialog', { name: /Oppsett for/ }).getByRole('button', { name: /^Bergen/ }).click()
await page.waitForFunction(() => { const st = JSON.parse(localStorage.getItem('hideandseek.v1')).state.settings; return st.city === 'bergen' && st.playArea?.length > 2 }, null, { timeout: 20000 })
s = await settings()
check(s.city === 'bergen' && s.areaAuto === true && s.playArea.length > 2, 'bytte til Bergen gir automatisk område igjen')
const bergenArea = JSON.stringify(s.playArea)
await page.getByRole('dialog', { name: /Oppsett for/ }).getByRole('radio', { name: 'Hele nettet' }).click()
await page.getByRole('dialog', { name: /Oppsett for/ }).getByRole('radio', { name: 'Automatisk' }).click()
await page.waitForTimeout(400)
s = await settings()
check(s.areaAuto === true && JSON.stringify(s.playArea) === bergenArea, '«Automatisk» gir samme område tilbake')
check(errors.length === 0, `ingen JS-feil ${errors.join(' | ')}`)
await browser.close()
console.log(failed ? `\n${failed} feilet` : '\nAlt OK')
process.exitCode = failed ? 1 : 0
